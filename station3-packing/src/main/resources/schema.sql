-- Station 3's own database
CREATE SCHEMA IF NOT EXISTS station3;

DROP TABLE IF EXISTS product_tray CASCADE;
DROP TABLE IF EXISTS part CASCADE;
DROP TABLE IF EXISTS product CASCADE;
DROP TABLE IF EXISTS tray CASCADE;

-- closed trays received from station 2 (the ids are station 2's)
CREATE TABLE tray
(
    id        INT PRIMARY KEY,
    part_type VARCHAR(50) NOT NULL
);

-- products are packed for distribution
CREATE TABLE product
(
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_type VARCHAR(20) NOT NULL -- PACKAGE or HALF_ANIMAL
);

-- the parts that came with the trays (the ids are station 2's), product_id is set when packed
CREATE TABLE part
(
    id         INT PRIMARY KEY,
    part_type  VARCHAR(50)      NOT NULL,
    weight_kg  DOUBLE PRECISION NOT NULL,
    tray_id    INT              NOT NULL REFERENCES tray (id),
    product_id INT REFERENCES product (id)
);

-- products are registered with references back to the trays the parts came from
CREATE TABLE product_tray
(
    product_id INT NOT NULL REFERENCES product (id),
    tray_id    INT NOT NULL REFERENCES tray (id),
    PRIMARY KEY (product_id, tray_id)
);
