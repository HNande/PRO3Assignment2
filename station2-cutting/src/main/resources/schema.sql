-- Station 2's own database
CREATE SCHEMA IF NOT EXISTS station2;

DROP TABLE IF EXISTS part CASCADE;
DROP TABLE IF EXISTS tray CASCADE;
DROP TABLE IF EXISTS animal CASCADE;

-- animals received from station 1
CREATE TABLE animal
(
    reg_no  VARCHAR(20) PRIMARY KEY,
    species VARCHAR(50) NOT NULL
);

-- a tray only holds one type of part
CREATE TABLE tray
(
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_type     VARCHAR(50)      NOT NULL,
    max_weight_kg DOUBLE PRECISION NOT NULL,
    closed        BOOLEAN          NOT NULL DEFAULT FALSE, -- full, no more parts go in
    forwarded     BOOLEAN          NOT NULL DEFAULT FALSE  -- has station 3 received it yet? (store-and-forward)
);

-- animals are cut into parts, each part goes into a tray
CREATE TABLE part
(
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_type     VARCHAR(50)      NOT NULL,
    weight_kg     DOUBLE PRECISION NOT NULL,
    animal_reg_no VARCHAR(20)      NOT NULL REFERENCES animal (reg_no),
    tray_id       INT              NOT NULL REFERENCES tray (id)
);
